// coverage.yaml: what in the product needs a manual page, and which page covers it.
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import YAML from 'yaml'
import { z } from 'zod'
import { formatIssues } from './config.ts'
import type { Page } from './pages.ts'

export const COVERAGE_FILE = 'coverage.yaml'

/**
 * Stored status. `ignored` and `manual-later` are set by people; `removed` by inventory; `mapped` / `unmapped` follow
 * `pages` (written by people) and `auto` (pages whose front matter names the item in `routes` or `covers`).
 */
export const CoverageStatus = z.enum(['mapped', 'unmapped', 'removed', 'ignored', 'manual-later'])
export type CoverageStatus = z.infer<typeof CoverageStatus>

export const CoverageItem = z.object({
  id: z.string(),
  kind: z.enum(['route', 'role', 'permission', 'section', 'flag']),
  label: z.string().optional(),
  source: z.string().optional(),
  status: CoverageStatus.default('unmapped'),
  pages: z.array(z.string()).default([]),
  /** Generated by inventory from page front matter; check recomputes it from the pages, so editing it does nothing. */
  auto: z.array(z.string()).default([]),
  note: z.string().optional(),
})
export type CoverageItem = z.infer<typeof CoverageItem>

const CoverageFile = z.object({ items: z.array(CoverageItem).default([]) })

export function readCoverage(manualDir: string): CoverageItem[] {
  const file = join(manualDir, COVERAGE_FILE)
  if (!existsSync(file)) return []
  const parsed = CoverageFile.safeParse(YAML.parse(readFileSync(file, 'utf8')) ?? {})
  if (!parsed.success) throw new Error(`Invalid ${COVERAGE_FILE}:\n${formatIssues(parsed.error.issues)}`)
  return parsed.data.items
}

/** The status that counts: people's choices win, then `removed`, then whether any page covers it (by hand or from front matter). */
export function effectiveStatus(item: Pick<CoverageItem, 'status' | 'pages'>, auto: string[] = []): CoverageStatus {
  if (item.status === 'ignored' || item.status === 'manual-later' || item.status === 'removed') return item.status
  return item.pages.length || auto.length ? 'mapped' : 'unmapped'
}

/**
 * Coverage id -> pages that name it in front matter: `routes: [/x]` covers `route:/x`, `covers:` lists ids or
 * `*` patterns. Primary-language pages only (twins share ids). `unmatched` lists covers entries that hit no id.
 */
export function autoPages(pages: Page[], primary: string, ids: string[]): { map: Map<string, string[]>; unmatched: { page: Page; entry: string }[] } {
  const map = new Map<string, string[]>()
  const unmatched: { page: Page; entry: string }[] = []
  const add = (id: string, page: string) => map.set(id, [...new Set([...(map.get(id) ?? []), page])].sort())
  for (const p of pages.filter((p) => p.lang === primary)) {
    for (const r of p.meta.routes) add(`route:${r}`, p.id)
    for (const entry of p.meta.covers) {
      const hits = ids.filter((id) => matchesAny(id, [entry]))
      if (!hits.length) unmatched.push({ page: p, entry })
      for (const id of hits) add(id, p.id)
    }
  }
  return { map, unmatched }
}

const HEADER = `# Generated by "manual-kit inventory". Map an item from the page instead when you can (front matter
# \`routes:\` or \`covers:\`, listed here as \`auto\`), or edit \`pages\` (page ids), or set \`status\` to
# ignored (with a note) or manual-later. Re-running inventory keeps your edits.
`

export function serializeCoverage(items: CoverageItem[]): string {
  const clean = items.map((i) => {
    const { id, kind, label, source, status, pages, auto, note } = i
    return { id, kind, ...(label ? { label } : {}), ...(source ? { source } : {}), status, pages, ...(auto.length ? { auto } : {}), ...(note ? { note } : {}) }
  })
  return HEADER + YAML.stringify({ items: clean }, { lineWidth: 0 })
}

/** `*` wildcard match on item ids. */
export function matchesAny(id: string, patterns: string[]): boolean {
  return patterns.some((p) => new RegExp(`^${p.split('*').map((s) => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&')).join('.*')}$`).test(id))
}
